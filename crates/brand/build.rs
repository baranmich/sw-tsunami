//! Reads the workspace's `brand.toml` (or `$BRAND_TOML`) and writes `$OUT_DIR/brand.rs`: the
//! product name and identifiers as constants, plus the `brand_name!()` macro, which expands to the
//! name as a string literal so it works inside `concat!`.

use std::path::PathBuf;

#[derive(serde::Deserialize)]
struct File {
    brand: Brand,
    identity: Identity,
    #[serde(default)]
    ui: Ui,
}

#[derive(serde::Deserialize)]
struct Ui {
    #[serde(default)]
    shell: String,
    #[serde(default = "yes")]
    neutral_terms: bool,
}

impl Default for Ui {
    fn default() -> Self {
        Self { shell: String::new(), neutral_terms: true }
    }
}

fn yes() -> bool {
    true
}

#[derive(serde::Deserialize)]
struct Brand {
    family: String,
    product: String,
    #[serde(default)]
    name: String,
    #[serde(default)]
    vendor: String,
    #[serde(default)]
    copyright: String,
    #[serde(default)]
    website: String,
    #[serde(default)]
    community_url: String,
    #[serde(default)]
    source_url: String,
}

#[derive(serde::Deserialize)]
struct Identity {
    bundle_id: String,
    data_dir: String,
    slug: String,
}

fn fail(msg: &str) -> ! {
    eprintln!("error: brand.toml: {msg}");
    std::process::exit(1);
}

fn main() {
    let path = match std::env::var_os("BRAND_TOML") {
        Some(p) => PathBuf::from(p),
        None => {
            let dir = std::env::var_os("CARGO_MANIFEST_DIR").unwrap_or_default();
            PathBuf::from(dir).join("../../brand.toml")
        }
    };
    println!("cargo:rerun-if-env-changed=BRAND_TOML");
    println!("cargo:rerun-if-changed={}", path.display());

    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| fail(&format!("can't read {}: {e}", path.display())));
    let f: File = toml::from_str(&text).unwrap_or_else(|e| fail(&e.to_string()));
    let b = f.brand;
    let id = f.identity;
    let shell = if f.ui.shell.trim().is_empty() { "ribbon".to_string() } else { f.ui.shell.trim().to_string() };
    if !matches!(shell.as_str(), "mac" | "ribbon") {
        fail("[ui] shell must be \"mac\" (toolbar, inspector, menu bar) or \"ribbon\" (upstream's Word-style ribbon)");
    }

    let name = if b.name.trim().is_empty() { format!("{} {}", b.family.trim(), b.product.trim()) } else { b.name.trim().to_string() };
    if name.trim().is_empty() {
        fail("the app needs a name: set [brand] family and product, or name");
    }
    if name.contains(['/', ':', '\\', '"']) || name.chars().any(char::is_control) {
        fail("the name becomes the macOS app and executable file name, so it can't contain / : \\ \" or control characters");
    }
    if name.contains("WordCraft") {
        fail("the name may not contain \"WordCraft\" (the upstream name that rebranding replaces)");
    }
    let id_ok = |s: &str| !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '.' || c == '-');
    if !id_ok(&id.bundle_id) {
        fail("[identity] bundle_id must be reverse-DNS letters, digits, dots and hyphens");
    }
    if !id_ok(&id.data_dir) {
        fail("[identity] data_dir must be letters, digits, dots and hyphens");
    }
    if id.slug.is_empty() || !id.slug.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-') {
        fail("[identity] slug must be lowercase letters, digits and hyphens");
    }

    let consts = [
        ("NAME", "Full display name, e.g. in the window title, menu bar and About.", name.as_str()),
        ("FAMILY", "Brand word shared by the app family.", b.family.trim()),
        ("PRODUCT", "This app's descriptor within the family.", b.product.trim()),
        ("VENDOR", "Legal owner.", b.vendor.trim()),
        ("COPYRIGHT", "Copyright line.", b.copyright.trim()),
        ("WEBSITE", "Product website; empty when there is none.", b.website.trim()),
        ("COMMUNITY_URL", "Community link (forum, Discord…); empty hides the community button.", b.community_url.trim()),
        ("SOURCE_URL", "Source code link; empty when there is none.", b.source_url.trim()),
        ("BUNDLE_ID", "Stable reverse-DNS app id (macOS bundle id, Wayland app id). Never changes with the name.", id.bundle_id.as_str()),
        ("DATA_DIR", "Stable name of the settings folder. Never changes with the name.", id.data_dir.as_str()),
        ("SLUG", "Stable lowercase machine name (MCP server name, storage keys).", id.slug.as_str()),
        ("SHELL", "Window shell: \"mac\" (toolbar, inspector, menu bar) or \"ribbon\" (upstream's ribbon).", shell.as_str()),
    ];
    let mut out = String::from("// Generated by build.rs from brand.toml. Do not edit.\n\n");
    for (k, doc, v) in consts {
        out.push_str(&format!("/// {doc}\npub const {k}: &str = {v:?};\n"));
    }
    out.push_str(&format!(
        "\n/// Whether third-party trademarks in interface text get the neutral names of brand/terms.tsv.\npub const NEUTRAL_TERMS: bool = {};\n",
        f.ui.neutral_terms
    ));
    out.push_str(&format!(
        "\n/// The display name as a string literal, for `concat!(brand_name!(), \" …\")`.\n#[macro_export]\nmacro_rules! brand_name {{\n    () => {{\n        {name:?}\n    }};\n}}\n"
    ));

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default());
    if let Err(e) = std::fs::write(out_dir.join("brand.rs"), out) {
        fail(&format!("can't write the generated file: {e}"));
    }
}
